def bits(row, width):
    v = 0
    for i, c in enumerate(row.ljust(width, '.')[:6]):
        if c == '#':
            v |= 0x80 >> i
    return v

def glyph(rows, width):
    rows = list(rows) + [""] * (8 - len(rows))
    return [bits(r, width) for r in rows[:8]]

def build():
    pat = [[0] * 8 for _ in range(256)]
    for code, rows in UI.items():
        pat[code] = glyph(rows, 6)
    for ch, rows in A.items():
        pat[ord(ch)] = glyph(rows, 5)
    for c in range(32, 127):
        g = list(pat[c])
        g[7] |= 0xFC                    # the underline: all six columns of row 7
        pat[c + 96] = g
    missing = [chr(c) for c in range(32, 127) if c != 32 and not any(pat[c])]
    assert not missing, missing
    return pat

def main():
    pat = build()
    out = os.path.join(ROOT, 'gen', 'font.a99')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as f:
        f.write('* gen/font.a99 - made by tools/font.py; do not edit\n')
        f.write('* 256 patterns x 8 bytes: UI 0-31, ASCII 32-126, Latin-1 marker 127,\n')
        f.write('* underlined ASCII 128-222, more UI 223-255\n')
        for c, g in enumerate(pat):
            f.write('       BYTE ' + ','.join('>%02X' % b for b in g) + '   %d\n' % c)
    print('wrote', out)

if __name__ == '__main__':
    main()
