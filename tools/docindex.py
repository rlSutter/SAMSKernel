#!/usr/bin/env python3
"""docindex.py - the routine reference from the kernel's header comments.

    python3 tools/docindex.py            write docs/ROUTINES.md
    python3 tools/docindex.py --check    fail if a routine that an application may
                                         call (listed in PUBLIC) has no header

A header is a comment line "* NAME - text" (or "* NAME / NAME2 - text") and the
comment lines after it, up to a blank comment line, the next header or code.
"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KERN = os.path.join(ROOT, 'kernel')
ORDER = ['loader', 'kernel', 'vdp', 'f18a', 'f18det', 'amsinit', 'pager', 'video', 'keys', 'text', 'modules', 'pool', 'files', 'music']
TITLES = {'vdp': 'VDP and the frame wait (vdp.a99)', 'f18a': 'The F18A (f18a.a99)', 'pager': 'SAMS paging (pager.a99)',
          'video': 'Text 80, colour schemes, the DMA row mover (video.a99)', 'keys': 'The keyboard (keys.a99)',
          'text': 'Text on the screen (text.a99)', 'modules': 'Modules (modules.a99)', 'pool': 'The page pool (pool.a99)',
          'files': 'Files (files.a99)', 'music': 'Music and sound (music.a99)', 'kernel': 'Main loop and exit (kernel.a99)', 'loader': 'The loader (loader.a99)',
          'f18det': 'F18A detection (f18det.a99, loader only)', 'amsinit': 'Memory card detection (amsinit.a99, loader only)'}
PUBLIC = [n for line in open(os.path.join(KERN, 'public.txt')) if not line.startswith('#') for n in line.split()]
HDR = re.compile(r'^\*\s+([A-Z][A-Z0-9]*(?:\s*/\s*[A-Z][A-Z0-9]*)*)\s+-\s+(.*)$')

def headers():
    out = {}
    for f in ORDER:
        lines = open(os.path.join(KERN, f + '.a99'), encoding='latin-1').read().split('\n')
        i = 0
        while i < len(lines):
            m = HDR.match(lines[i])
            if m:
                names = [n.strip() for n in m.group(1).split('/')]
                text = [m.group(2).strip()]
                i += 1
                while i < len(lines) and lines[i].startswith('*') and lines[i].strip() not in ('*',) and not HDR.match(lines[i]) \
                        and not lines[i].startswith('*==') and not lines[i].startswith('*--'):
                    text.append(lines[i][1:].strip()); i += 1
                for n in names:
                    out[n] = (f, ' '.join(text))
            else:
                i += 1
    return out

def main():
    h = headers()
    if '--check' in sys.argv:
        miss = [n for n in PUBLIC if n not in h]
        if miss: sys.exit('no header: ' + ' '.join(miss))
        print('every public routine has a header'); return
    L = ['# SAMS Kernel: routine reference', '', '**Routes.** Every routine here is available to both routes: **[PC]** (a cartridge built with `skbuild.py`) and **[TI]** (a program assembled in the workbench); `MUPLAY` needs a song in SAMS pages, so it is **[PC]**. The assembly source is the same either way.', '',
         'Generated by `tools/docindex.py` from the header comments in `kernel/`; the comments are canonical.',
         'Registers listed as "Uses" are every register the routine can change, including through what it calls.',
         'Routines marked *leaf* never call another routine and may be called with a bare `BL`.', '']
    for f in ORDER:
        items = [(n, t) for n, (ff, t) in h.items() if ff == f]
        if not items: continue
        L += ['## ' + TITLES[f], '']
        for n, t in items:
            tag = '' if n in PUBLIC else ' *(internal)*'
            L += ['### `%s`%s' % (n, tag), '', t, '']
    open(os.path.join(ROOT, 'docs', 'ROUTINES.md'), 'w').write('\n'.join(L))
    print('wrote docs/ROUTINES.md: %d routines' % len(h))

if __name__ == '__main__':
    main()
